// Writes the native play scripts (tests/native/*.play) by playing the rules
// (js/rules.js) in Node with the greedy bot rules.js validateContent uses and
// emitting the inputs a player would give: tool keys (1–3, W, H; a tool's key
// again would put it down, so only changes are pressed), arrows to the plot and
// Enter, Space to wait, and clicks on the exact Craft / Fulfill button names
// (native/screens.ts). Turn-based, so the scripts only wait a couple of frames
// between inputs.   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const R = createRequire(import.meta.url)('../js/rules.js');
const NAMES = { turnip: 'Turnip', carrot: 'Carrot', pumpkin: 'Pumpkin', salad: 'Garden Salad', pie: 'Harvest Pie' };
const TOOL_KEY = { turnip: 'Digit1', carrot: 'Digit2', pumpkin: 'Digit3', water: 'KeyW', harvest: 'KeyH' };

/** The bot's next command (rules.js validateContent's need-aware greedy). */
function pick(state) {
  const legal = R.legalActions(state);
  const unmet = {};
  for (const o of state.orders) for (const [k, n] of Object.entries(o.needs)) unmet[k] = Math.max(unmet[k] || 0, n - (state.inventory[k] || 0));
  return legal.find((a) => a.type === 'fulfill') || legal.find((a) => a.type === 'harvest') || legal.find((a) => a.type === 'water')
    || legal.find((a) => a.type === 'craft' && unmet[a.recipe] > 0)
    || legal.filter((a) => a.type === 'plant' && unmet[a.crop] > 0).sort((a, b) => unmet[b.crop] - unmet[a.crop])[0]
    || legal.find((a) => a.type === 'plant') || legal.find((a) => a.type === 'craft') || { type: 'wait' };
}

/** Lines that play `config` to its end with the keyboard (and clicks for crafting and orders). */
function playLines(config, { maxActions = Infinity, touch = false, drawers = false } = {}) {
  let state = R.createSession(config);
  const lines = [];
  let tool = null, sel = -1, n = state.plots.length, id = 0;
  const key = (code) => { lines.push(`key ${code} 1`, 'frames 2'); };
  const tap = (label) => { lines.push('frames 3', `${touch ? 'touch' : 'click'} =${label}`, 'frames 4'); };
  // Compact layouts keep the orders (left) and crafting (right) in drawers.
  const click = (label, side) => {
    if (drawers) tap(side === 'left' ? 'Open objective and orders panel' : 'Open inventory and actions panel');
    tap(label);
    if (drawers) tap('Close panel');
  };
  while (!state.terminalReason && id < maxActions) {
    const a = pick(state);
    if (a.type === 'wait') key('Space');
    else if (a.type === 'craft') {
      const r = R.RECIPES[a.recipe];
      click(`Craft ${NAMES[a.recipe]} from ${Object.entries(r.needs).map(([k, c]) => `${c} ${NAMES[k]}`).join(' + ')}`, 'right');
    } else if (a.type === 'fulfill') {
      const o = state.orders.find((x) => x.id === a.orderId);
      click(`Fulfill order for ${Object.entries(o.needs).map(([k, c]) => `${c}× ${NAMES[k]}`).join(', ')}, reward ${o.reward} coins`, 'left');
    } else {
      const t = a.type === 'plant' ? a.crop : a.type;
      if (tool !== t) { key(TOOL_KEY[t]); tool = t; }
      if (sel < 0) { key('ArrowRight'); sel = 1 % n; }
      const fwd = (a.plot - sel + n) % n, back = (sel - a.plot + n) % n;
      for (let i = 0; i < Math.min(fwd, back); i++) key(fwd <= back ? 'ArrowRight' : 'ArrowLeft');
      sel = a.plot;
      key('Enter');
    }
    const res = R.apply(state, { id: 'g' + (id++), type: a.type, plot: a.plot, crop: a.crop, recipe: a.recipe, orderId: a.orderId });
    if (!res.ok) throw new Error('bot command rejected: ' + res.reason);
    state = res.state;
  }
  return { lines, state };
}

const learn = R.defaultConfig('learn', 'learn-seed', { maxTicks: 60, goalOrders: 2, plotCount: 8, allowedCrops: ['turnip', 'carrot'], allowedRecipes: [], difficulty: 'easy', assists: { hints: true, undo: true } });
